fn is_valid_identifier(s: &str) -> bool {
    if s.is_empty() {
        return false;
    }
    let mut chars = s.chars();
    match chars.next() {
        Some(c) if c.is_ascii_alphabetic() || c == '_' => {}
        _ => return false,
    }
    chars.all(|c| c.is_ascii_alphanumeric() || c == '_')
}

pub fn is_valid_luau_identifier(s: &str) -> bool {
    is_valid_identifier(s) && !LUAU_RESERVED.contains(&s)
}

fn is_valid_ts_identifier(s: &str) -> bool {
    is_valid_identifier(s) && !TS_RESERVED.contains(&s)
}

pub fn format_key(key: &str) -> String {
    if is_valid_luau_identifier(key) {
        key.to_string()
    } else {
        format!("[\"{}\"]", key.replace('\\', "\\\\").replace('"', "\\\""))
    }
}

fn format_ts_key(key: &str) -> String {
    if is_valid_ts_identifier(key) {
        key.to_string()
    } else {
        format!("\"{}\"", key.replace('\\', "\\\\").replace('"', "\\\""))
    }
}

/// Format a key for the LHS of a Luau type field. Quoted form for non-idents.
fn format_luau_type_key(key: &str) -> String {
    if is_valid_luau_identifier(key) {
        key.to_string()
    } else {
        format!("[\"{}\"]", key.replace('\\', "\\\\").replace('"', "\\\""))
    }
}

// ---------------------------------------------------------------------------
// Tree types — per-env IDs and the shape union
// ---------------------------------------------------------------------------

pub type CodegenTree = BTreeMap<String, CodegenNode>;

#[derive(Debug)]
pub enum CodegenNode {
    Leaf(u64),
    Branch(BTreeMap<String, CodegenNode>),
}

/// Same shape as `CodegenTree` but stripped of leaf values, used to describe
/// the union of all envs' shapes for type emission and 0-stub padding.
pub type ShapeTree = BTreeMap<String, ShapeNode>;

#[derive(Debug)]
pub enum ShapeNode {
    Leaf,
    Branch(BTreeMap<String, ShapeNode>),
}

fn insert_into_tree(tree: &mut CodegenTree, segments: &[&str], key: &str, id: u64) {
    if segments.is_empty() {
        tree.insert(key.to_string(), CodegenNode::Leaf(id));
        return;
    }
    let node = tree
        .entry(segments[0].to_string())
        .or_insert_with(|| CodegenNode::Branch(BTreeMap::new()));
    match node {
        CodegenNode::Branch(children) => {
            insert_into_tree(children, &segments[1..], key, id);
        }
        CodegenNode::Leaf(_) => {
            let mut children = BTreeMap::new();
            insert_into_tree(&mut children, &segments[1..], key, id);
            *node = CodegenNode::Branch(children);
        }
    }
}

fn insert_item(tree: &mut CodegenTree, path_str: &str, key: &str, id: u64, flat: bool) {
    if flat {
        let flat_key = format!("{path_str}.{key}");
        tree.insert(flat_key, CodegenNode::Leaf(id));
    } else {
        let segments: Vec<&str> = path_str.split('.').collect();
        insert_into_tree(tree, &segments, key, id);
    }
}

fn resolve_path<'a>(item_path: Option<&'a str>, section_default: &'a str) -> &'a str {
    item_path.unwrap_or(section_default)
}

/// Build a CodegenTree for a single env from its lockfile section + the
/// config-level codegen options.
pub fn build_env_tree(env_lock: &EnvLock, config: &Config) -> CodegenTree {
    let mut tree = CodegenTree::new();
    let flat = config.codegen.style == CodegenStyle::Flat;

    let default_pass_path = config.codegen.paths.passes.as_deref().unwrap_or("passes");
    let default_badge_path = config.codegen.paths.badges.as_deref().unwrap_or("badges");
    let default_product_path = config
        .codegen
        .paths
        .products
        .as_deref()
        .unwrap_or("products");

    for (key, lock) in &env_lock.passes {
        let path_str = resolve_path(
            config.passes.get(key).and_then(|c| c.path.as_deref()),
            default_pass_path,
        );
        insert_item(&mut tree, path_str, key, lock.id, flat);
    }

    for (key, lock) in &env_lock.badges {
        let path_str = resolve_path(
            config.badges.get(key).and_then(|c| c.path.as_deref()),
            default_badge_path,
        );
        insert_item(&mut tree, path_str, key, lock.id, flat);
    }

    for (key, lock) in &env_lock.products {
        let path_str = resolve_path(
            config.products.get(key).and_then(|c| c.path.as_deref()),
            default_product_path,
        );
        insert_item(&mut tree, path_str, key, lock.id, flat);
    }

    for (full_key, &id) in &config.codegen.extra {
        if flat {
            tree.insert(full_key.clone(), CodegenNode::Leaf(id));
        } else if let Some(dot_pos) = full_key.rfind('.') {
            let path_str = &full_key[..dot_pos];
            let leaf_key = &full_key[dot_pos + 1..];
            let segments: Vec<&str> = path_str.split('.').collect();
            insert_into_tree(&mut tree, &segments, leaf_key, id);
        } else {
            tree.insert(full_key.clone(), CodegenNode::Leaf(id));
        }
    }

    tree
}

// ---------------------------------------------------------------------------
// Shape union + 0-stub padding
// ---------------------------------------------------------------------------

fn extract_shape(tree: &CodegenTree) -> ShapeTree {
    let mut out = ShapeTree::new();
    for (k, v) in tree {
        match v {
            CodegenNode::Leaf(_) => {
                out.insert(k.clone(), ShapeNode::Leaf);
            }
            CodegenNode::Branch(children) => {
                out.insert(k.clone(), ShapeNode::Branch(extract_shape(children)));
            }
        }
    }
    out
}

fn merge_shape(into: &mut ShapeTree, other: &ShapeTree) {
    for (k, v) in other {
        match (into.get_mut(k), v) {
            (Some(ShapeNode::Branch(into_children)), ShapeNode::Branch(other_children)) => {
                merge_shape(into_children, other_children);
            }
            (Some(ShapeNode::Leaf), ShapeNode::Leaf) => {}
            (Some(_), _) => {
                // Conflicting kinds (leaf vs branch) — keep `into`'s kind.
                // Should not happen with well-formed configs.
            }
            (None, ShapeNode::Leaf) => {
                into.insert(k.clone(), ShapeNode::Leaf);
            }
            (None, ShapeNode::Branch(children)) => {
                into.insert(k.clone(), ShapeNode::Branch(clone_shape(children)));
            }
        }
    }
}

fn clone_shape(children: &ShapeTree) -> ShapeTree {
    let mut out = ShapeTree::new();
    for (k, v) in children {
        out.insert(
            k.clone(),
            match v {
                ShapeNode::Leaf => ShapeNode::Leaf,
                ShapeNode::Branch(c) => ShapeNode::Branch(clone_shape(c)),
            },
        );
    }
    out
}

/// Walk `shape` and ensure every leaf path is present in `tree` (inserting
/// `Leaf(0)` for missing ones).
fn pad_with_zeros(tree: &mut CodegenTree, shape: &ShapeTree) {
    for (k, sv) in shape {
        match sv {
            ShapeNode::Leaf => {
                if !tree.contains_key(k) {
                    tree.insert(k.clone(), CodegenNode::Leaf(0));
                }
            }
            ShapeNode::Branch(shape_children) => {
                let entry = tree
                    .entry(k.clone())
                    .or_insert_with(|| CodegenNode::Branch(BTreeMap::new()));
                if let CodegenNode::Branch(tree_children) = entry {
                    pad_with_zeros(tree_children, shape_children);
                }
            }
        }
    }
}

/// Build the union shape across all envs.
fn build_union_shape(env_trees: &[(String, CodegenTree)]) -> ShapeTree {
    let mut union = ShapeTree::new();
    for (_, tree) in env_trees {
        let shape = extract_shape(tree);
        merge_shape(&mut union, &shape);
    }
    union
}

