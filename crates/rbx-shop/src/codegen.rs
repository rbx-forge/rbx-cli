/// Header on every file this module emits.
///
/// Kept as constants rather than spelled out at each site: the banner is on its
/// way to being load-bearing — stale-file pruning refuses to delete anything
/// that does not carry `@generated` — and a copy that drifts would break that
/// recognition without failing anything.
///
/// Names the tool, not the subcommand, because `sync` and `codegen` both emit
/// this folder. `rbx env` names `gen-module` for the opposite reason: it is the
/// only thing there that writes a file.
const LUAU_HEADER: &str = "\
-- This file is automatically @generated by rbx shop.
-- It is not intended for manual editing.
";

const TS_HEADER: &str = "\
// This file is automatically @generated by rbx shop.
// It is not intended for manual editing.
";

/// The token the banner is recognized by. Nothing without it is ever deleted
/// as stale, so a hand-written file that wandered into the output folder is
/// left alone.
///
/// `@generated` rather than a product name: it is the convention review tools
/// recognize, and it survives the CLI being renamed.
const GENERATED_MARKER: &str = "@generated";

/// Same banner, naming the env the module carries. Worth the divergence: in
/// Studio the file is an instance inside a folder, so the header restates what
/// the file name says once the name is no longer in view.
fn luau_header_for_env(env_name: &str) -> String {
    format!(
        "-- This file is automatically @generated by rbx shop for env '{env_name}'.\n\
         -- It is not intended for manual editing.\n"
    )
}

