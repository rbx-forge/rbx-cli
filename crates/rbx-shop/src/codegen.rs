/// Everything a codegen run would do, computed without touching the
/// filesystem beyond looking for leftovers.
///
/// `generate` and `codegen --check` both go through this, which is the whole
/// point: a verifier that re-described what the writer emits would drift from
/// it, and a check with false positives gets switched off.
#[derive(Debug)]
pub struct CodegenPlan {
    /// Absolute path of the output folder.
    pub dir: PathBuf,
    /// Files this run produces, in write order.
    pub files: Vec<GeneratedFile>,
    /// Files we generated previously that this run no longer produces — a
    /// renamed or deleted env, or `typescript` turned off. Left behind, they
    /// are dead modules that still look generated.
    pub stale: Vec<PathBuf>,
    /// Number of envs rendered.
    pub env_count: usize,
}

/// Compute the codegen plan. `Ok(None)` when there is nothing to generate:
/// either `[codegen].output` is unset, or the lockfile has no envs yet.
pub fn plan(
    config: &Config,
    lockfile: &Lockfile,
    config_dir: &Path,
) -> Result<Option<CodegenPlan>> {
    let Some(output) = &config.codegen.output else {
        return Ok(None);
    };
    let output_path = config_dir.join(output);

    if let Some(name) = output.file_name().and_then(|s| s.to_str()) {
        let lower = name.to_ascii_lowercase();
        let stripped_len = if lower.ends_with(".luau") {
            Some(name.len() - 5)
        } else if lower.ends_with(".lua") {
            Some(name.len() - 4)
        } else {
            None
        };
        if let Some(len) = stripped_len {
            bail!(
                "[codegen].output = \"{}\" looks like a file path, not a folder — it names a \
                 FOLDER that will contain init.luau and per-env modules, so it shouldn't end in \
                 a Luau extension. Remove the extension, e.g. \"{}\".",
                output.display(),
                output.with_file_name(&name[..len]).display()
            );
        }
    }

    if lockfile.envs.is_empty() {
        return Ok(None);
    }

    // Names derived from the folder name (PascalCase by convention).
    //   output = "src/shared/GameIds" → var_name = "GameIds"
    //   wrapper_name = lower-first → "gameIds"
    //   type_module_name = "<var_name>Type" → "GameIdsType"
    let var_name = derive_var_name(&output_path);
    let wrapper_name = lower_first(&var_name);
    let type_module_name = format!("{}Type", var_name);

    // Per-env modules are written as `<env>.luau` next to init.luau and the
    // type module — an env named after either would silently clobber it.
    for env_name in lockfile.envs.keys() {
        if env_name == "init" || *env_name == type_module_name {
            bail!(
                "Env name '{env_name}' collides with the generated {env_name}.luau module. \
                 Rename the env in rbxplace.toml or change codegen.output."
            );
        }
        if env_name.contains(['/', '\\']) || env_name == "." || env_name == ".." {
            bail!("Env name '{env_name}' is not usable as a codegen file name.");
        }
    }

    // Build per-env trees
    let mut env_trees: Vec<(String, CodegenTree)> = Vec::new();
    let mut env_universes: Vec<(String, u64)> = Vec::new();
    for (env_name, env_lock) in &lockfile.envs {
        let tree = build_env_tree(env_lock, config);
        env_trees.push((env_name.clone(), tree));
        env_universes.push((env_name.clone(), env_lock.universe_id));
    }

    // Compute union shape and pad each env tree with 0-stubs for missing entries.
    let union_shape = build_union_shape(&env_trees);
    for (_, tree) in &mut env_trees {
        pad_with_zeros(tree, &union_shape);
    }

    let style_is_flat = config.codegen.style == CodegenStyle::Flat;

    let mut files = Vec::new();

    // <var_name>Type.luau (type + wrapper function)
    files.push(GeneratedFile::new(
        output_path.join(format!("{}.luau", type_module_name)),
        render_type_module(&union_shape, &var_name, &wrapper_name, style_is_flat),
    ));

    // init.luau (dispatcher)
    files.push(GeneratedFile::new(
        output_path.join("init.luau"),
        render_init_luau(&env_universes, &var_name, &type_module_name),
    ));

    // Per-env modules (each wraps its data with Types.<wrapper>(...))
    for (env_name, tree) in &env_trees {
        let has_stubs = tree_contains_zero(tree);
        files.push(GeneratedFile::new(
            output_path.join(format!("{}.luau", env_name)),
            render_env_module(tree, env_name, has_stubs, &type_module_name, &wrapper_name),
        ));
    }

    // init.d.ts if requested
    if config.codegen.typescript {
        files.push(GeneratedFile::new(
            output_path.join("init.d.ts"),
            render_init_dts(&union_shape, &var_name, style_is_flat),
        ));
    }

    let stale = find_stale(&output_path, &files)?;

    Ok(Some(CodegenPlan {
        dir: output_path,
        files,
        stale,
        env_count: env_trees.len(),
    }))
}

/// Files in `dir` that we generated on an earlier run but that this plan no
/// longer produces.
///
/// Only files that could plausibly be ours are considered, and each one must
/// still carry [`GENERATED_MARKER`] in its header — pruning deletes files, so
/// it errs entirely on the side of leaving things alone.
fn find_stale(dir: &Path, files: &[GeneratedFile]) -> Result<Vec<PathBuf>> {
    if !dir.is_dir() {
        return Ok(Vec::new());
    }

    let expected: BTreeSet<OsString> = files
        .iter()
        .filter_map(|f| f.path.file_name().map(|n| n.to_os_string()))
        .collect();

    let mut stale = Vec::new();
    let entries = std::fs::read_dir(dir)
        .with_context(|| format!("Failed to read codegen folder {}", dir.display()))?;

    for entry in entries {
        let entry = entry?;
        if !entry.file_type()?.is_file() {
            continue;
        }
        let name = entry.file_name();
        if expected.contains(&name) {
            continue;
        }
        let Some(name) = name.to_str() else { continue };
        let could_be_ours = name.ends_with(".luau") || name.ends_with(".d.ts");
        if !could_be_ours {
            continue;
        }
        if is_generated(&entry.path()) {
            stale.push(entry.path());
        }
    }

    stale.sort();
    Ok(stale)
}

/// Whether a file carries our header. Unreadable files answer `false`: better
/// to leave a stale module behind than to delete something we did not write.
fn is_generated(path: &Path) -> bool {
    std::fs::read_to_string(path)
        .map(|content| {
            content
                .lines()
                .take(4)
                .any(|line| line.contains(GENERATED_MARKER))
        })
        .unwrap_or(false)
}

/// Render and write the codegen folder, pruning anything we generated
/// previously that the current inputs no longer produce.
pub fn generate(config: &Config, lockfile: &Lockfile, config_dir: &Path) -> Result<()> {
    let Some(plan) = plan(config, lockfile, config_dir)? else {
        return Ok(());
    };

    std::fs::create_dir_all(&plan.dir)
        .with_context(|| format!("Failed to create codegen folder {}", plan.dir.display()))?;

    for file in &plan.files {
        file.write()?;
    }

    for path in &plan.stale {
        std::fs::remove_file(path)
            .with_context(|| format!("Failed to remove stale {}", path.display()))?;
        println!("{} Removed stale {}", "-".yellow(), path.display());
    }

    println!(
        "{} Generated codegen at {} ({} env{})",
        "✓".green(),
        plan.dir.display(),
        plan.env_count,
        if plan.env_count == 1 { "" } else { "s" }
    );

    Ok(())
}
