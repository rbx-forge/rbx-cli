/// Derive the Luau type/variable name from the output folder path.
/// Defaults to "GameIds" if the path has no useful component or the component
/// isn't a valid Luau identifier.
fn derive_var_name(output_path: &Path) -> String {
    output_path
        .file_name()
        .and_then(|s| s.to_str())
        .filter(|s| is_valid_luau_identifier(s))
        .map(|s| s.to_string())
        .unwrap_or_else(|| "GameIds".to_string())
}

/// Lower-case the first ASCII character, keep the rest unchanged.
/// `"GameIds"` → `"gameIds"`, `"Assets"` → `"assets"`.
fn lower_first(s: &str) -> String {
    let mut chars = s.chars();
    match chars.next() {
        Some(c) => c.to_ascii_lowercase().to_string() + chars.as_str(),
        None => String::new(),
    }
}

