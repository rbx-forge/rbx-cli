// Rendering — TypeScript (.d.ts)
// ---------------------------------------------------------------------------

fn render_ts_type_node(out: &mut String, node: &ShapeNode, depth: usize) {
    let indent = "\t".repeat(depth);
    match node {
        ShapeNode::Leaf => {
            out.push_str("number\n");
        }
        ShapeNode::Branch(children) => {
            out.push_str("{\n");
            for (key, child) in children {
                out.push_str(&format!("{indent}\t{}: ", format_ts_key(key)));
                render_ts_type_node(out, child, depth + 1);
            }
            out.push_str(&format!("{indent}}}\n"));
        }
    }
}

fn render_init_dts(shape: &ShapeTree, var_name: &str, style_is_flat: bool) -> String {
    let mut out = String::new();
    out.push_str(TS_HEADER);
    out.push('\n');
    out.push_str(&format!("declare const {}: {{\n", var_name));
    if style_is_flat {
        for key in shape.keys() {
            out.push_str(&format!("\t{}: number\n", format_ts_key(key)));
        }
    } else {
        for (key, node) in shape {
            out.push_str(&format!("\t{}: ", format_ts_key(key)));
            render_ts_type_node(&mut out, node, 1);
        }
    }
    out.push_str("}\n\n");
    out.push_str(&format!("export = {}\n", var_name));
    out
}

