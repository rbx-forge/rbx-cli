fn render_luau_type_node(out: &mut String, node: &ShapeNode, depth: usize) {
    let indent = "\t".repeat(depth);
    match node {
        ShapeNode::Leaf => {
            out.push_str("number,\n");
        }
        ShapeNode::Branch(children) => {
            out.push_str("{\n");
            for (key, child) in children {
                out.push_str(&format!("{indent}\t{}: ", format_luau_type_key(key)));
                render_luau_type_node(out, child, depth + 1);
            }
            out.push_str(&format!("{indent}}},\n"));
        }
    }
}

fn render_init_luau(
    env_universes: &[(String, u64)],
    var_name: &str,
    type_module_name: &str,
) -> String {
    let mut out = String::new();
    out.push_str(LUAU_HEADER);
    out.push('\n');

    // Re-export the type from the sibling Types module so consumers can do
    // `type Ids = GameIds.<var_name>` after a single require.
    out.push_str(&format!(
        "local Types = require(script.{})\n",
        type_module_name
    ));
    out.push_str(&format!(
        "export type {name} = Types.{name}\n\n",
        name = var_name
    ));

    // String-literal union of env names — required for `never`-exhaustiveness
    // narrowing in the if/elseif dispatcher below.
    out.push_str("export type EnvName = ");
    let env_literals: Vec<String> = env_universes
        .iter()
        .map(|(name, _)| format!("\"{}\"", name.replace('"', "\\\"")))
        .collect();
    out.push_str(&env_literals.join(" | "));
    out.push_str("\n\n");

    // Universe → env lookup. The value type is EnvName (not a plain string)
    // so the narrowing in the dispatcher works.
    out.push_str("local UNIVERSE_TO_ENV: { [number]: EnvName } = {\n");
    for (env_name, universe_id) in env_universes {
        out.push_str(&format!(
            "\t[{}] = \"{}\",\n",
            universe_id,
            env_name.replace('"', "\\\"")
        ));
    }
    out.push_str("}\n\n");

    // Exhaustiveness helper. Calling this with a `never` argument is only
    // type-safe when every variant of EnvName has been narrowed away by an
    // earlier branch. Adding a new env to EnvName without an accompanying
    // elseif fails to compile in strict mode.
    out.push_str(
        "local function exhaustiveMatch(value: never): never\n\
         \terror(`rbxshop: unhandled env in dispatcher: {value :: any}`)\n\
         end\n\n",
    );

    // Resolve the env from the running universe.
    out.push_str("local env = UNIVERSE_TO_ENV[game.GameId]\n");
    out.push_str("if not env then\n");
    out.push_str("\terror(`rbxshop: unknown universe {game.GameId}`)\n");
    out.push_str("end\n\n");

    // if/elseif/else dispatcher with exhaustive fallback.
    for (idx, (env_name, _)) in env_universes.iter().enumerate() {
        let keyword = if idx == 0 { "if" } else { "elseif" };
        let env_child = if is_valid_luau_identifier(env_name) {
            format!("script.{}", env_name)
        } else {
            format!("script[\"{}\"]", env_name.replace('"', "\\\""))
        };
        out.push_str(&format!(
            "{} env == \"{}\" then\n\treturn require({})\n",
            keyword,
            env_name.replace('"', "\\\""),
            env_child
        ));
    }
    out.push_str(
        "else\n\
         \texhaustiveMatch(env)\n\
         \terror(\"luau\")\n\
         end\n",
    );

    out
}

