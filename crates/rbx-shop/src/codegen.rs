// Rendering — per-env Luau module (value tables)
// ---------------------------------------------------------------------------

fn render_luau_value_node(out: &mut String, node: &CodegenNode, depth: usize) {
    let indent = "\t".repeat(depth);
    match node {
        CodegenNode::Leaf(id) => {
            out.push_str(&format!("{id},\n"));
        }
        CodegenNode::Branch(children) => {
            out.push_str("{\n");
            for (key, child) in children {
                out.push_str(&format!("{indent}\t{} = ", format_key(key)));
                render_luau_value_node(out, child, depth + 1);
            }
            out.push_str(&format!("{indent}}},\n"));
        }
    }
}

fn render_env_module(
    tree: &CodegenTree,
    env_name: &str,
    has_stubs: bool,
    type_module_name: &str,
    wrapper_name: &str,
) -> String {
    let mut out = String::new();
    out.push_str(&luau_header_for_env(env_name));
    if has_stubs {
        // Worth the one extra line: a reader who finds `VIP = 0` has no other
        // way to tell a stub from a real id, and prompting one is a silent
        // no-op rather than an error.
        out.push_str("-- Entries with the value 0 are stubs: absent from this env.\n");
    }
    out.push('\n');
    out.push_str(&format!(
        "local Types = require(script.Parent.{})\n\n",
        type_module_name
    ));
    out.push_str(&format!("return Types.{}({{\n", wrapper_name));
    for (key, node) in tree {
        out.push_str(&format!("\t{} = ", format_key(key)));
        render_luau_value_node(&mut out, node, 1);
    }
    out.push_str("})\n");
    out
}

/// Render the Type module that holds `export type <Name>` plus the wrapper
/// identity function used by per-env modules for compile-time shape validation.
fn render_type_module(
    shape: &ShapeTree,
    var_name: &str,
    wrapper_name: &str,
    style_is_flat: bool,
) -> String {
    let mut out = String::new();
    out.push_str(LUAU_HEADER);
    out.push('\n');

    // Type alias
    out.push_str(&format!("export type {} = ", var_name));
    if style_is_flat {
        out.push_str("{\n");
        for key in shape.keys() {
            out.push_str(&format!("\t{}: number,\n", format_luau_type_key(key)));
        }
        out.push_str("}\n\n");
    } else {
        out.push_str("{\n");
        for (key, node) in shape {
            out.push_str(&format!("\t{}: ", format_luau_type_key(key)));
            render_luau_type_node(&mut out, node, 1);
        }
        out.push_str("}\n\n");
    }

    // Wrapper identity function — Luau-strict mode validates the literal at
    // every call site against the type.
    out.push_str(&format!(
        "local function {wrapper}(x: {ty}): {ty}\n\treturn x\nend\n\n",
        wrapper = wrapper_name,
        ty = var_name,
    ));

    out.push_str(&format!(
        "return {{\n\t{} = {},\n}}\n",
        wrapper_name, wrapper_name
    ));
    out
}

fn tree_contains_zero(tree: &CodegenTree) -> bool {
    for v in tree.values() {
        match v {
            CodegenNode::Leaf(0) => return true,
            CodegenNode::Branch(children) if tree_contains_zero(children) => return true,
            _ => {}
        }
    }
    false
}

